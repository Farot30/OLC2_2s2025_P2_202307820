void crearArchivoStringValueOfInt(const char* ruta) {
    FILE* f = fopen(ruta, "w");
    if (!f) return;

    // Rutina ARM64 para String.valueOf(int)
    fprintf(f,
        ".global valueOf_int\n"
        "\n"
        ".section .rodata\n"
        "intmin_str: .asciz \"2147483648\"\n"
        "\n"
        "valueOf_int:\n"
        "    STP X29, X30, [SP, #-16]!\n"
        "    STP X19, X20, [SP, #-16]!\n"
        "    STP X21, X22, [SP, #-16]!\n"
        "    MOV X19, X1\n"
        "    MOV W20, W0\n"
        "    MOV X21, X1\n"
        "    MOV X22, #0\n"
        "    CBNZ W0, vi_check_negative\n"
        "    MOV W2, #'0'\n"
        "    STRB W2, [X19], #1\n"
        "    MOV W2, #0\n"
        "    STRB W2, [X19]\n"
        "    MOV X0, X21\n"
        "    MOV X1, #1\n"
        "    B vi_end\n"
        "vi_check_negative:\n"
        "    CMP W20, #0\n"
        "    B.GE vi_positive\n"
        "    MOV W2, #'-'\n"
        "    STRB W2, [X19], #1\n"
        "    ADD X22, X22, #1\n"
        "    MOV W3, #0x8000\n"
        "    MOVK W3, #0x0000, LSL #16\n"
        "    CMP W20, W3\n"
        "    B.NE vi_regular_negative\n"
        "    ADR X2, intmin_str\n"
        "    MOV X3, #10\n"
        "vi_copy_intmin:\n"
        "    LDRB W4, [X2], #1\n"
        "    STRB W4, [X19], #1\n"
        "    SUBS X3, X3, #1\n"
        "    B.NE vi_copy_intmin\n"
        "    MOV W4, #0\n"
        "    STRB W4, [X19]\n"
        "    MOV X0, X21\n"
        "    MOV X1, #11\n"
        "    B vi_end\n"
        "vi_regular_negative:\n"
        "    NEG W20, W20\n"
        "    B vi_positive\n"
        "vi_positive:\n"
        "    MOV X2, X19\n"
        "    MOV W3, #10\n"
        "vi_extract_loop:\n"
        "    UDIV W4, W20, W3\n"
        "    MSUB W5, W4, W3, W20\n"
        "    ADD W5, W5, #'0'\n"
        "    STRB W5, [X2], #1\n"
        "    ADD X22, X22, #1\n"
        "    MOV W20, W4\n"
        "    CBNZ W20, vi_extract_loop\n"
        "    MOV W5, #0\n"
        "    STRB W5, [X2]\n"
        "    MOV X19, X21\n"
        "    ADD X19, X19, X22\n"
        "    SUB X19, X19, #1\n"
        "    MOV X2, X21\n"
        "vi_reverse_loop:\n"
        "    CMP X2, X19\n"
        "    B.GE vi_finish\n"
        "    LDRB W5, [X2]\n"
        "    LDRB W6, [X19]\n"
        "    STRB W6, [X2], #1\n"
        "    STRB W5, [X19], #-1\n"
        "    B vi_reverse_loop\n"
        "vi_finish:\n"
        "    MOV X0, X21\n"
        "    MOV X1, X22\n"
        "vi_end:\n"
        "    LDP X21, X22, [SP], #16\n"
        "    LDP X19, X20, [SP], #16\n"
        "    LDP X29, X30, [SP], #16\n"
        "    RET\n"
    );

    fclose(f);
}

